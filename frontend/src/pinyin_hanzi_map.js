// Universal Pinyin to Hanzi converter
export function convertPinyinToHanzi(inputStr) {
  if (!inputStr) return '';
  let str = String(inputStr).trim();
  
  // If text already has Chinese characters, keep as is
  if (/[\u4e00-\u9fa5]/.test(str)) {
    return str;
  }

  // Clean punctuation / notes like "iou (-iu)"
  str = str.replace(/\([^\)]*\)/g, '').trim();
  const cleanKey = str.replace(/['’\s-]/g, '').toLowerCase();

  // 1. Direct dictionary match
  if (PINYIN_TO_HANZI[cleanKey]) {
    return PINYIN_TO_HANZI[cleanKey];
  }
  if (PINYIN_TO_HANZI[str.toLowerCase()]) {
    return PINYIN_TO_HANZI[str.toLowerCase()];
  }

  // 2. Syllable Segmentation Engine for multi-syllable words (e.g. nǐhǎo, báibǐ, kāfèi, píngguǒ, etc.)
  let remaining = cleanKey;
  let resultHanzi = '';

  while (remaining.length > 0) {
    let matched = false;

    // Try longest matching substring from remaining start
    for (let len = remaining.length; len >= 1; len--) {
      const sub = remaining.substring(0, len);
      if (PINYIN_TO_HANZI[sub]) {
        resultHanzi += PINYIN_TO_HANZI[sub];
        remaining = remaining.substring(len);
        matched = true;
        break;
      }
    }

    if (!matched) {
      resultHanzi += remaining[0];
      remaining = remaining.substring(1);
    }
  }

  return resultHanzi || str;
}
